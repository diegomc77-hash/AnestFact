/**
 * Regenera data/proformas-bundle.js (índice + todas las proformas).
 * Uso: node tools/bundle-proformas.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'data', 'proformas');
const OUT = path.join(ROOT, 'data', 'proformas-bundle.js');

function walk(d, acc) {
  for (const n of fs.readdirSync(d).sort()) {
    const p = path.join(d, n);
    if (fs.statSync(p).isDirectory()) walk(p, acc);
    else if (n.endsWith('.js') && n !== 'index.js') acc.push(p);
  }
  return acc;
}

const files = walk(DIR, []);
let out =
  '/* auto-generated by tools/bundle-proformas.mjs — ~' +
  Math.round(
    (fs.readFileSync(path.join(DIR, 'index.js'), 'utf8').length +
      files.reduce((a, f) => a + fs.statSync(f).size, 0)) /
      1024
  ) +
  ' KB */\n' +
  fs.readFileSync(path.join(DIR, 'index.js'), 'utf8') +
  '\n';
for (const f of files) out += fs.readFileSync(f, 'utf8') + '\n';
fs.writeFileSync(OUT, out);
console.log('OK', OUT, Math.round(out.length / 1024) + 'KB', files.length + ' proformas');
